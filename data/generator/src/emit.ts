import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { TABLE_NAMES, TABLE_SCHEMAS } from '@fpa/semantic';
import type { TableName } from '@fpa/semantic';
import { z } from 'zod';
import type { Dataset } from './index';

const esc = (v: unknown): string => {
  if (v === null || v === undefined) return '';
  const s = String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export function toCsv(table: TableName, rows: Array<Record<string, unknown>>): string {
  const cols = Object.keys(TABLE_SCHEMAS[table].shape);
  return (
    [cols.join(','), ...rows.map((r) => cols.map((c) => esc(r[c])).join(','))].join('\n') + '\n'
  );
}

export function renderOutputs(ds: Dataset): Record<string, string> {
  const out: Record<string, string> = {};
  const manifest: Record<string, { rows: number; sha256: string }> = {};
  for (const t of TABLE_NAMES) {
    const csv = toCsv(t, ds.tables[t]);
    out[`fixtures/${t}.csv`] = csv;
    manifest[t] = {
      rows: ds.tables[t].length,
      sha256: createHash('sha256').update(csv).digest('hex'),
    };
  }
  out['fixtures/MANIFEST.json'] =
    JSON.stringify(
      {
        generator_version: (ds.golden.meta as { generator_version: string }).generator_version,
        tables: manifest,
      },
      null,
      2,
    ) + '\n';
  out['golden/nov2026.json'] = JSON.stringify(ds.golden, null, 2) + '\n';
  out['golden/questions.json'] = JSON.stringify(ds.questions, null, 2) + '\n';
  return out;
}

export function writeOutputs(ds: Dataset, dataDir: string): void {
  for (const [rel, content] of Object.entries(renderOutputs(ds))) {
    const path = join(dataDir, rel);
    mkdirSync(join(path, '..'), { recursive: true });
    writeFileSync(path, content);
  }
}

/** Returns the list of files that differ from (or are missing in) the committed fixtures. */
export function diffOutputs(ds: Dataset, dataDir: string): string[] {
  return Object.entries(renderOutputs(ds))
    .filter(
      ([rel, content]) =>
        !existsSync(join(dataDir, rel)) || readFileSync(join(dataDir, rel), 'utf8') !== content,
    )
    .map(([rel]) => rel);
}

function unwrap(s: z.ZodTypeAny): { base: z.ZodTypeAny; nullable: boolean; desc?: string } {
  let cur = s;
  let nullable = false;
  let desc = s.description;
  while (cur instanceof z.ZodNullable || cur instanceof z.ZodOptional) {
    nullable = true;
    cur = cur._def.innerType;
    desc = desc ?? cur.description;
  }
  return { base: cur, nullable, desc: desc ?? cur.description };
}
function label(b: z.ZodTypeAny): string {
  if (b instanceof z.ZodNumber) return b.isInt ? 'integer' : 'number';
  if (b instanceof z.ZodString) return 'text';
  if (b instanceof z.ZodBoolean) return 'boolean';
  if (b instanceof z.ZodEnum) return `enum: ${(b.options as string[]).join(' / ')}`;
  if (b instanceof z.ZodLiteral) return `literal: ${String(b.value)}`;
  return 'value';
}

export function renderDictionary(ds: Dataset): string {
  const lines = [
    '# Data dictionary (generated)',
    '',
    '> Generated by `pnpm data:generate` from `@fpa/semantic`. Do not edit by hand. All data is **synthetic**; company, customer and supplier names are fictional.',
    '',
    'Money is stored as **integer rupees (INR)**. 1 crore = 10,000,000. Revenue and costs are both stored as positive amounts; `dim_account.type` gives the meaning. Fiscal year FY27 = April 2026 to March 2027.',
    '',
  ];
  for (const t of TABLE_NAMES) {
    lines.push(
      `## ${t}`,
      '',
      `Rows: ${ds.tables[t].length.toLocaleString('en-US')}`,
      '',
      '| Column | Type | Description |',
      '|---|---|---|',
    );
    for (const [col, schema] of Object.entries(TABLE_SCHEMAS[t].shape)) {
      const { base, nullable, desc } = unwrap(schema as z.ZodTypeAny);
      lines.push(`| \`${col}\` | ${label(base)}${nullable ? ' (nullable)' : ''} | ${desc ?? ''} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}
